const Joi = require('joi');

const baseEnvelope = {
  params: Joi.object({}).default({}),
  query: Joi.object({}).default({}),
};

const createProductSchema = Joi.object({
  body: Joi.object({
    name: Joi.string().min(3).max(255).required(),
    slug: Joi.string().min(3).max(255).required(),
    sku: Joi.string().min(2).max(100).optional(),  // optional — auto-generated by service if omitted
    description: Joi.string().max(5000).allow(''),
    price: Joi.number().positive().precision(2).required(),
    compare_price: Joi.number().positive().precision(2).allow(null),
    stock_qty: Joi.number().integer().min(0).default(0),
    category_id: Joi.string().allow('', null),
    collection_id: Joi.string().allow('', null),
    is_published: Joi.boolean().default(false),
    is_featured: Joi.boolean().default(false),
    tags: Joi.array().items(Joi.string()).default([]),
    attributes: Joi.object().default({}),
    meta_title: Joi.string().max(255).allow('', null),
    meta_desc: Joi.string().max(500).allow('', null),
  }).required(),
  ...baseEnvelope,
});

const enquirySchema = Joi.object({
  body: ({
    name: Joi.string().min(2).max(100).required(),

    email: Joi.string().email().required(),

    phone: Joi.string()
      .pattern(/^[0-9]{10}$/)
      .required(),

    message: Joi.string().allow("").optional(),

    // product_id: Joi.string().required(),
    // product_name: Joi.string().required(),
    products: Joi.array()
      .items(
        Joi.object({
          product_id: Joi.string().required(),
          quantity: Joi.number().integer().min(1).default(1),
        })
      )
      .min(1)
      .required(),

    use_whatsapp: Joi.boolean().optional(),

    whatsapp_number: Joi.when("use_whatsapp", {
      is: true,
      then: Joi.string()
        .pattern(/^[0-9]{10}$/)
        .required()
        .messages({
          "string.pattern.base": "WhatsApp number must be 10 digits",
        }),
      otherwise: Joi.optional().allow(null, ""),
    }),
    tenant_id: Joi.string().optional(),
  })

});

const productIdParamsSchema = Joi.object({
  params: Joi.object({
    productId: Joi.string().required(),
  }).required(),
  body: Joi.object({}).default({}),
  query: Joi.object({}).default({}),
});

const updateProductSchema = Joi.object({
  params: Joi.object({
    productId: Joi.string().required(),
  }).required(),
  body: Joi.object({
    name: Joi.string().min(3).max(255),
    slug: Joi.string().min(3).max(255),
    // sku intentionally excluded from update — it is immutable once generated
    description: Joi.string().max(5000).allow(''),
    price: Joi.number().positive().precision(2),
    compare_price: Joi.number().positive().precision(2).allow(null),
    stock_qty: Joi.number().integer().min(0),
    category_id: Joi.string().allow('', null),
    collection_id: Joi.string().allow('', null),
    is_published: Joi.boolean(),
    is_featured: Joi.boolean(),
    tags: Joi.array().items(Joi.string()),
    attributes: Joi.object(),
    meta_title: Joi.string().max(255).allow('', null),
    meta_desc: Joi.string().max(500).allow('', null),
  })
    .min(1)
    .required(),
  query: Joi.object({}).default({}),
});

const getProductsSchema = Joi.object({
  query: Joi.object({
    page: Joi.number().integer().min(1).default(1),
    limit: Joi.number().integer().min(1).max(100).default(10),
    category_id: Joi.string().allow('', null),
    is_published: Joi.boolean(),
    is_featured: Joi.boolean(),
    search: Joi.string().max(255).allow('', null),
    sort_by: Joi.string().valid('created_at', 'name', 'price').default('created_at'),
    sort_order: Joi.string().valid('asc', 'desc').default('desc'),
  }).required(),
  body: Joi.object({}).default({}),
  params: Joi.object({}).default({}),
});

// Public storefront listing — deliberately separate from getProductsSchema
// (admin) because the query shape/semantics differ: single `sort` string
// instead of sort_by/sort_order, plus shopper-facing filters like category,
// rating, inStock, minPrice/maxPrice.
const getPublicProductsSchema = Joi.object({
  query: Joi.object({
    page: Joi.number().integer().min(1).default(1),
    limit: Joi.number().integer().min(1).max(100).default(12),
    search: Joi.string().trim().max(255).allow('', null),
    // Comma-separated category IDs, e.g. ?category=id1,id2
    category: Joi.string().max(1000).allow('', null),
    rating: Joi.number().min(0).max(5).default(0),
    inStock: Joi.boolean().default(false),
    minPrice: Joi.number().min(0),
    maxPrice: Joi.number().min(0).when('minPrice', {
      is: Joi.exist(),
      then: Joi.number().min(Joi.ref('minPrice')),
    }),
    sort: Joi.string()
      .valid('newest', 'price-asc', 'price-desc', 'name-asc', 'name-desc', 'rating', 'popularity')
      .default('newest'),
  }).required(),
  body: Joi.object({}).default({}),
  params: Joi.object({}).default({}),
});

const updateProductImagesSchema = Joi.object({
  params: Joi.object({
    productId: Joi.string().required(),
  }).required(),
  body: Joi.object({
    primary_image_id: Joi.string().allow('', null),
  }).required(),
  query: Joi.object({}).default({}),
});

const deleteProductImageSchema = Joi.object({
  params: Joi.object({
    productId: Joi.string().required(),
    imageId: Joi.string().required(),
  }).required(),
  body: Joi.object({}).default({}),
  query: Joi.object({}).default({}),
});

const heroBannerFields = {
  source_type: Joi.string().valid('product_image', 'uploaded'),
  product_image_id: Joi.string().allow('', null),
  image_alt_text: Joi.string().max(255).allow('', null),
  start_at: Joi.date().iso().allow('', null),
  end_at: Joi.date().iso().allow('', null),
  is_published: Joi.boolean(),
};

const heroBannerIdSchema = Joi.object({
  params: Joi.object({ bannerId: Joi.string().required() }).required(),
  body: Joi.object({}).default({}),
  query: Joi.object({}).default({}),
});

const createHeroBannerSchema = Joi.object({
  params: Joi.object({}).default({}),
  query: Joi.object({}).default({}),
  body: Joi.object({
    banner_type: Joi.string().valid('default', 'campaign').required(),
    ...heroBannerFields,
  }).required(),
});

const updateHeroBannerSchema = Joi.object({
  params: Joi.object({ bannerId: Joi.string().required() }).required(),
  query: Joi.object({}).default({}),
  body: Joi.object(heroBannerFields).min(1).required(),
});

const publishHeroBannerSchema = Joi.object({
  params: Joi.object({ bannerId: Joi.string().required() }).required(),
  query: Joi.object({}).default({}),
  body: Joi.object({ is_published: Joi.boolean().required() }).required(),
});

const reorderHeroBannersSchema = Joi.object({
  params: Joi.object({}).default({}),
  query: Joi.object({}).default({}),
  body: Joi.object({
    banner_type: Joi.string().valid('default', 'campaign').required(),
    ordered_ids: Joi.array().items(Joi.string().required()).max(6).required(),
  }).required(),
});

const generateReviewInvitationSchema = Joi.object({
  params: Joi.object({
    enquiryId: Joi.string().required(),
  }).required(),
  body: Joi.object({}).default({}),
  query: Joi.object({}).default({}),
});

const submitReviewSchema = Joi.object({
  params: Joi.object({
    inviteCode: Joi.string().required(),
  }).required(),
  body: Joi.object({
    rating: Joi.number().integer().min(1).max(5).required(),
    review: Joi.string().allow("").max(3000),
  }).required(),
  query: Joi.object({}).default({}),
});

const reviewParamsSchema = Joi.object({
  params: Joi.object({
    productId: Joi.string().required(),
  }).required(),
  body: Joi.object({}).default({}),
  query: Joi.object({}).default({}),
});

module.exports = {
  createProductSchema,
  enquirySchema,
  updateProductSchema,
  productIdParamsSchema,
  getProductsSchema,
  getPublicProductsSchema,
  updateProductImagesSchema,
  deleteProductImageSchema,
  heroBannerIdSchema,
  createHeroBannerSchema,
  updateHeroBannerSchema,
  publishHeroBannerSchema,
  reorderHeroBannersSchema,
  generateReviewInvitationSchema,
  submitReviewSchema,
  reviewParamsSchema,
};
